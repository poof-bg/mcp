// Writes src/version.ts and the server.json versions (MCP Registry) from
// package.json. Runs automatically on `npm version`.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const { version } = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
writeFileSync(
  new URL('../src/version.ts', import.meta.url),
  `// Generated by scripts/sync-version.mjs from package.json. Do not edit.\nexport const VERSION = '${version}';\n`,
);

const serverJsonUrl = new URL('../server.json', import.meta.url);
if (existsSync(serverJsonUrl)) {
  const text = readFileSync(serverJsonUrl, 'utf8');
  const server = JSON.parse(text);
  // Only the server version and the npm package version change; edit them in
  // place so the rest of the file keeps its formatting.
  let updated = text.replace(/^(  "version": )"[^"]*"/m, `$1"${version}"`);
  if (server.packages?.some((p) => p.identifier === '@poof-bg/mcp')) {
    updated = updated.replace(
      /("identifier": "@poof-bg\/mcp",\s*(?:"[^"]+": [^,\n]+,\s*)*?"version": )"[^"]*"/,
      `$1"${version}"`,
    );
  }
  writeFileSync(serverJsonUrl, updated);
}
